#!/usr/bin/env python3
"""Dependency-free MCP bridge for a local DeepSeek model served by Ollama."""

from __future__ import annotations

import json
import os
import re
import sys
import urllib.error
import urllib.request
from urllib.parse import urlparse
from typing import Any

from command_deck_bridge import (
    CommandDeckBridgeError,
    call_command_deck_tool,
    list_command_deck_tools,
)


SERVER_NAME = "deepseek-harness"
SERVER_VERSION = "0.3.0-local"
OLLAMA_URL = "http://127.0.0.1:11434"
DEFAULT_MODEL = "deepseek-r1:1.5b"
DEFAULT_KEEP_ALIVE = "15m"


