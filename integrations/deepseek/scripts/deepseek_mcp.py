def emit(message: dict[str, Any]) -> None:
    sys.stdout.write(json.dumps(message, ensure_ascii=False, separators=(",", ":")) + "\n")
    sys.stdout.flush()


def tool_error(
    message: str, metadata: dict[str, Any] | None = None
) -> dict[str, Any]:
    result: dict[str, Any] = {
        "content": [{"type": "text", "text": message}],
        "isError": True,
    }
    if metadata is not None:
        result["structuredContent"] = metadata
    return result


def seconds_from_nanoseconds(value: Any) -> float | None:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    return round(value / 1_000_000_000, 3)


def tokens_per_second(token_count: Any, duration_ns: Any) -> float | None:
    if (
        isinstance(token_count, bool)
        or not isinstance(token_count, (int, float))
        or isinstance(duration_ns, bool)
        or not isinstance(duration_ns, (int, float))
        or duration_ns <= 0
    ):
        return None
    return round(token_count / (duration_ns / 1_000_000_000), 2)


def validate_arguments(arguments: Any) -> tuple[dict[str, Any] | None, str | None]:
    if not isinstance(arguments, dict):
        return None, "Tool arguments must be an object."

    prompt = arguments.get("prompt")
    if not isinstance(prompt, str) or not prompt.strip():
        return None, "prompt must be a non-empty string."

    system_prompt = arguments.get("system_prompt")
    if system_prompt is not None and not isinstance(system_prompt, str):
        return None, "system_prompt must be a string."

    max_tokens = arguments.get("max_output_tokens", 4096)
    if isinstance(max_tokens, bool) or not isinstance(max_tokens, int):
        return None, "max_output_tokens must be an integer."
    if not 1 <= max_tokens <= 16384:
        return None, "max_output_tokens must be between 1 and 16384."

    model = os.environ.get("DEEPSEEK_LOCAL_MODEL", DEFAULT_MODEL).strip()
    if not model.startswith("deepseek-r1:"):
        return None, "DEEPSEEK_LOCAL_MODEL must name a local deepseek-r1 model."

    return {
        "prompt": prompt.strip(),
        "system_prompt": system_prompt.strip() if system_prompt else None,
        "model": model,
        "max_output_tokens": max_tokens,
    }, None


def call_deepseek(arguments: Any) -> dict[str, Any]:
    args, validation_error = validate_arguments(arguments)
    if validation_error:
        return tool_error(validation_error)
    assert args is not None

    parsed_url = urlparse(OLLAMA_URL)
    if parsed_url.hostname not in {"127.0.0.1", "localhost", "::1"}:
        return tool_error("The harness is restricted to a local Ollama server.")

    try:
        timeout = float(os.environ.get("DEEPSEEK_TIMEOUT_SECONDS", "300"))
    except ValueError:
        return tool_error("DEEPSEEK_TIMEOUT_SECONDS must be numeric.")
    if not 1 <= timeout <= 600:
        return tool_error("DEEPSEEK_TIMEOUT_SECONDS must be between 1 and 600.")

    keep_alive = os.environ.get("DEEPSEEK_KEEP_ALIVE", DEFAULT_KEEP_ALIVE).strip()
    if not re.fullmatch(r"-?\d+(?:\.\d+)?(?:ms|s|m|h)?", keep_alive):
        return tool_error(
            "DEEPSEEK_KEEP_ALIVE must be a duration such as 0, 15m, or 1h."
        )

    messages: list[dict[str, str]] = []
    if args["system_prompt"]:
        messages.append({"role": "system", "content": args["system_prompt"]})
    messages.append({"role": "user", "content": args["prompt"]})

    payload = {
        "model": args["model"],
        "messages": messages,
        "stream": False,
        "keep_alive": keep_alive,
        "options": {"num_predict": args["max_output_tokens"]},
    }
    request = urllib.request.Request(
        f"{OLLAMA_URL}/api/chat",
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Content-Type": "application/json",
            "User-Agent": f"{SERVER_NAME}/{SERVER_VERSION}",
        },
        method="POST",
    )

    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            data = json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        details = exc.read(4096).decode("utf-8", errors="replace")
        return tool_error(f"Local Ollama returned HTTP {exc.code}: {details}")
    except urllib.error.URLError as exc:
        return tool_error(
            "Could not reach local Ollama at http://127.0.0.1:11434. "
            f"Make sure Ollama is running. Details: {exc.reason}"
        )
    except (TimeoutError, json.JSONDecodeError) as exc:
        return tool_error(f"Local Ollama response error: {exc}")

    message = data.get("message")
    if not isinstance(message, dict):
        return tool_error("Local Ollama returned an unexpected response shape.")

    answer = message.get("content")
    if not isinstance(answer, str):
        return tool_error("Local DeepSeek returned no textual answer.")

    thinking = message.get("thinking")
    thinking_chars = len(thinking) if isinstance(thinking, str) else 0

    # Some DeepSeek-R1 builds embed internal reasoning in <think> blocks.
    answer = re.sub(r"<think>.*?</think>\s*", "", answer, flags=re.DOTALL).strip()
    metadata = {
        "model": data.get("model", args["model"]),
        "local": True,
        "done_reason": data.get("done_reason"),
        "prompt_tokens": data.get("prompt_eval_count"),
        "completion_tokens": data.get("eval_count"),
        "prompt_tokens_per_second": tokens_per_second(
            data.get("prompt_eval_count"), data.get("prompt_eval_duration")
        ),
        "completion_tokens_per_second": tokens_per_second(
            data.get("eval_count"), data.get("eval_duration")
        ),
        "load_seconds": seconds_from_nanoseconds(data.get("load_duration")),
        "total_seconds": seconds_from_nanoseconds(data.get("total_duration")),
        "thinking_characters": thinking_chars,
        "answer_characters": len(answer),
    }

    if not answer:
        if data.get("done_reason") == "length" and thinking_chars:
            return tool_error(
                "Local DeepSeek used the output budget for reasoning before it produced "
                "a final answer. Retry with a larger max_output_tokens value.",
                metadata,
            )
        return tool_error("Local DeepSeek returned no final answer.", metadata)

    return {
        "content": [{"type": "text", "text": answer}],
        "structuredContent": metadata,
    }


def command_deck_tools() -> dict[str, Any]:
    try:
        tools = list_command_deck_tools()
    except CommandDeckBridgeError as exc:
        return tool_error(str(exc))

    catalog = [
        {
            "name": tool.get("name"),
            "title": tool.get("title"),
            "description": tool.get("description"),
            "inputSchema": tool.get("inputSchema"),
            "readOnly": bool(
                isinstance(tool.get("annotations"), dict)
                and tool["annotations"].get("readOnlyHint") is True
            ),
        }
        for tool in tools
    ]
    return {
        "content": [
            {
                "type": "text",
                "text": json.dumps(catalog, ensure_ascii=False, indent=2),
            }
        ],
        "structuredContent": {
            "server": "command-deck",
            "tool_count": len(catalog),
            "tools": catalog,
        },
    }


def command_deck_call(arguments: Any) -> dict[str, Any]:
    if not isinstance(arguments, dict):
        return tool_error("Tool arguments must be an object.")
    name = arguments.get("tool")
    if not isinstance(name, str) or not name.strip():
        return tool_error("tool must be a non-empty string.")
    tool_arguments = arguments.get("arguments", {})
    if not isinstance(tool_arguments, dict):
        return tool_error("arguments must be an object.")
    allow_state_changes = arguments.get("allow_state_changes", False)
    if not isinstance(allow_state_changes, bool):
        return tool_error("allow_state_changes must be a boolean.")

    try:
        result, bridge_metadata = call_command_deck_tool(
            name.strip(), tool_arguments, allow_state_changes
        )
    except CommandDeckBridgeError as exc:
        return tool_error(str(exc))

    content = result.get("content")
    if not isinstance(content, list):
        content = [
            {
                "type": "text",
                "text": json.dumps(result, ensure_ascii=False, indent=2),
            }
        ]
    response: dict[str, Any] = {
        "content": content,
        "structuredContent": {
            **bridge_metadata,
            "command_deck_result": result.get("structuredContent"),
        },
    }
    if result.get("isError") is True:
        response["isError"] = True
    return response


def handle_request(request: dict[str, Any]) -> dict[str, Any] | None:
    method = request.get("method")
    request_id = request.get("id")

    if request_id is None:
        return None

    if method == "initialize":
        params = request.get("params") or {}
        protocol_version = params.get("protocolVersion", "2024-11-05")
        result = {
            "protocolVersion": protocol_version,
            "capabilities": {"tools": {"listChanged": False}},
            "serverInfo": {"name": SERVER_NAME, "version": SERVER_VERSION},
        }
    elif method == "ping":
        result = {}
    elif method == "tools/list":
        result = {
            "tools": [
                CONSULT_TOOL,
                COMMAND_DECK_TOOLS_TOOL,
                COMMAND_DECK_CALL_TOOL,
            ]
        }
    elif method == "tools/call":
        params = request.get("params") or {}
        if params.get("name") == "consult":
            result = call_deepseek(params.get("arguments", {}))
        elif params.get("name") == "command_deck_tools":
            result = command_deck_tools()
        elif params.get("name") == "command_deck_call":
            result = command_deck_call(params.get("arguments", {}))
        else:
            result = tool_error(f"Unknown tool: {params.get('name')}")
    else:
        return {
            "jsonrpc": "2.0",
            "id": request_id,
            "error": {"code": -32601, "message": f"Method not found: {method}"},
        }

    return {"jsonrpc": "2.0", "id": request_id, "result": result}


def main() -> None:
    for raw_line in sys.stdin:
        if not raw_line.strip():
            continue
        try:
            request = json.loads(raw_line)
            if not isinstance(request, dict):
                raise ValueError("request must be an object")
            response = handle_request(request)
        except (json.JSONDecodeError, ValueError) as exc:
            response = {
                "jsonrpc": "2.0",
                "id": None,
                "error": {"code": -32700, "message": f"Parse error: {exc}"},
            }
        except Exception as exc:  # Keep the MCP process alive after an unexpected request error.
            response = {
                "jsonrpc": "2.0",
                "id": request.get("id") if isinstance(request, dict) else None,
                "error": {"code": -32603, "message": f"Internal error: {exc}"},
            }
        if response is not None:
            emit(response)


if __name__ == "__main__":
    main()
